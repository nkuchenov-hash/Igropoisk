#!/usr/bin/env node
import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=path=>fs.readFileSync(path,'utf8');
const json=path=>JSON.parse(read(path));
const contract=json('config/review-commercial-contract.json');
assert.ok(Number(contract.article?.minimum_words)>=3000,'commercial article minimum must be at least 3000 words');
assert.ok(Number(contract.game_media?.minimum_unique_screenshots)>=15,'game media minimum must be at least 15 screenshots');
assert.ok(Number(contract.game_media?.target_unique_screenshots)>=20,'game media target must be at least 20 screenshots');
assert.equal(contract.game_media?.artwork_must_never_enter_screenshot_pool,true,'artwork must be separate from screenshots');
assert.equal(contract.lifecycle?.forbid_attempt_exhaustion_for_released_games,true,'released games must never exhaust enrichment attempts');
assert.equal(contract.lifecycle?.forbid_terminal_deferred_for_missing_material,true,'missing material must never become terminal deferred');
assert.equal(contract.lifecycle?.keep_searching_until_complete,true,'commercial lifecycle must keep searching until complete');
assert.ok(String(contract.source_corpus?.fallback_rule||'').length>40,'below-preferred exhaustive fallback rule is required');
const post=read('.github/workflows/game-post-create-enrichment.yml');
const manual=read('.github/workflows/review-synthesis.yml');
assert.ok(post.includes('run-commercial-review-contract.mjs'),'post-create workflow must use unified commercial orchestrator');
assert.ok(manual.includes('run-commercial-review-contract.mjs'),'manual review workflow must use the same commercial orchestrator');
const legacy=read('scripts/run-game-post-create-enrichment.mjs');
for(const forbidden of ['deferred_to_catalog_lifecycle','POST_CREATE_MAX_ATTEMPTS','build-review-bootstrap-local.mjs','quality-control-loop.mjs'])assert.ok(!legacy.includes(forbidden),`legacy enrichment path still contains forbidden bypass: ${forbidden}`);
const validator=read('scripts/validate-commercial-review-v2.mjs');
assert.ok(validator.includes('exhaustive_discovery'),'validator must understand exhaustive below-preferred fallback');
assert.ok(!validator.includes("status:'blocked'"),'validator must not emit terminal blocked state');
const media=read('scripts/enforce-commercial-game-media.mjs');
assert.ok(!media.includes("status:'blocked'"),'media enrichment must not emit terminal blocked state');
const overlay=read('scripts/publish-game-post-create-overlay.mjs');
assert.ok(overlay.includes("'data/review-article-corpus'"),'overlay must persist article corpus between retry passes');
assert.ok(overlay.includes("'data/review-discovery-audits'"),'overlay must persist discovery audit between retry passes');
console.log('Commercial review contract v2 static boundary passed.');

export function buildEditorialAudienceContext(draft={},parser={}){
  const classification=draft?.classification||{};
  const explicitAge=clean(
    classification.age_rating||classification.content_rating||classification.esrb||classification.pegi||
    draft?.age_rating||draft?.content_rating||parser?.age_rating||parser?.content_rating||''
  );
  const official=[
    parser?.editorial?.short_description,
    parser?.editorial?.integrated_description,
    draft?.editorial?.short_description,
    draft?.editorial?.integrated_description
  ].map(clean).filter(Boolean).join(' ').slice(0,1200);
  return {
    explicit_age_rating:explicitAge||null,
    genres:list(classification.genres),
    categories:list(classification.categories),
    tone_evidence:official||null,
    rule:'Адаптируй только регистр и акценты, которые подтверждаются этими данными. Не придумывай возрастную аудиторию или тон.'
  };
}

export function editorialSurfaceRule(surface){
  if(surface==='short_description')return 'TEASER: 1–2 предложения. Сразу покажи отличительную игровую фантазию/идею. Это high-impact текст: он должен цеплять конкретикой, а не рекламными эпитетами.';
  if(surface==='integrated_description')return 'ОБ ИГРЕ: сформируй цельную ментальную модель игры — что делает игрок, как устроен основной цикл/развитие, что отличает игру и почему это влияет на ощущение от неё. Не пересказывай store description по предложениям.';
  if(surface==='campaign')return 'PROGRESSION: описывай реальную структуру прохождения или развития. Не изобретай сюжетную кампанию. Если отдельной кампании нет, описывай подтверждённую структуру развития/сессий/забегов.';
  if(surface==='features')return 'FEATURES: каждый пункт — конкретная система, решение, структура мира или взаимодействие механик. Никаких «уникальной атмосферы», «динамичного геймплея» и platform/store capabilities.';
  if(surface==='review')return 'REVIEW: отдельный большой редакционный материал. Нужны аргументированная позиция, синтез source corpus, причины достоинств/недостатков, связная композиция и конкретные примеры без выдумки.';
  return 'Пиши в каноническом стиле Игропоиска и адаптируй регистр только по подтверждённому audience/tone context.';
}
